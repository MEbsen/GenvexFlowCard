import assert from "node:assert/strict";
import fs from "node:fs";
const { fanModel } = await import(`data:text/javascript;base64,${fs.readFileSync("src/fan-model.js").toString("base64")}`);
const calls = [];
const make = (state, config = {}, entity = "number.speed") => fanModel({ entity, state: { state, attributes: {} }, config, callService: (...args) => calls.push(args) });
assert.equal(make("2", { min: 0, max: 5, mode: "steps" }).normalizedPercent, 40);
assert.equal(make("5", { min: 0, max: 5, mode: "steps" }).options.length, 6);
assert.equal(make("0.5", { min: 0, max: 1, step: 0.05 }).normalizedPercent, 50);
assert.equal(make("1500", { min: 500, max: 2500 }).normalizedPercent, 60);
assert.equal(make("999", { min: 0, max: 100 }).normalizedPercent, 100);
for (const state of ["unknown", "unavailable", "", null]) {
  const model = make(state);
  assert.equal(model.available, false);
  assert.equal(model.running, null);
  assert.equal(model.displayValue, "—");
}
const named = make("medium", { min: 0, max: 100, options: ["off", "low", "medium", "high"] }, "select.speed");
assert.ok(Math.abs(named.normalizedPercent - 200 / 3) < 1e-8);
named.setValue("high");
assert.deepEqual(calls.pop(), ["select", "select_option", { entity_id: "select.speed", option: "high" }]);
named.setValue("invalid");
assert.equal(calls.length, 0);
make("0.5", { min: 0, max: 1, step: 0.05 }).setValue(0.63);
assert.equal(calls.pop()[2].value, 0.65);
const fan = fanModel({ entity: "fan.speed", state: { state: "off", attributes: { percentage: 70, percentage_step: 5 } }, callService: (...args) => calls.push(args) });
assert.equal(fan.running, false);
assert.equal(fan.step, 5);
fan.setValue(73);
assert.equal(calls.pop()[2].percentage, 75);
make("unavailable").setValue(10);
assert.equal(calls.length, 0);
assert.throws(() => make("0", { min: 5, max: 5 }));
assert.throws(() => make("0", { step: 0 }));
const lowest=make("1",{min:1,max:5,mode:"steps"});
assert.equal(lowest.running,true);
assert.equal(lowest.normalizedPercent,20);
const uneven=make("medium",{min:0,max:100,option_values:{off:0,low:15,medium:45,high:100},options:["off","low","medium","high"]},"select.speed");
assert.equal(uneven.normalizedPercent,45);
assert.equal(make("low",{options:["low","medium","high"]},"select.speed").running,true);
assert.equal(make("2",{min:0,max:5},"sensor.speed").writable,false);
assert.equal(make("2",{min:0,max:5},"sensor.speed").setValue(3),undefined);
assert.throws(()=>make("1",{off_value:5,max:5}));
assert.throws(()=>make("on",{min:0,max:1},"fan.speed"));
console.log("Fan model tests OK");
